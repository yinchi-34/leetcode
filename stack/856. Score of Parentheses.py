"""
题目理解：
    本质上是一个嵌套结构，与树、递归表达式类似：
    一个括号内部还可以继续包含括号。

    因为存在嵌套关系，可以使用栈保存每一层括号当前累计的分数。
    Python 中使用 list 模拟 stack。

    st[i] 表示第 i 层当前已经计算出的分数。

遇到 '('：
    进入下一层，压入 0，表示新的一层暂时没有分数。

遇到 ')'：
    当前层结束，弹出当前层分数 v：
    - 如果 v == 0，说明当前结构是 ()，分数为 1
    - 如果 v > 0，说明当前结构是 (A)，分数为 2 * v

    然后把当前括号结构的分数累加到上一层。

最终 st[0] 即整个字符串的分数。
"""
class Solution:
    def scoreOfParentheses(self, s: str) -> int:
        #
        st = [0]
        for c in s:
            if c == '(':
                st.append(0)
            else:
                v = st.pop()
                st[-1] += max(2 * v, 1)

        return st[-1]